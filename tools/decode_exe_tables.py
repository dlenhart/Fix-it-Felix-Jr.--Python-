"""Decode the exe's sprite-frame and building-piece tables.

Usage: python3 -I tools/decode_exe_tables.py FixitFelixJr.exe

Records are 10 bytes, little-endian ``<5h`` = [id, x, y, w, h] in 8px cells.
Each record's id must equal its index; that is the alignment check, and the
script exits non-zero if it fails.
"""
import json
import os
import struct
import sys

os.environ.setdefault("SDL_VIDEODRIVER", "dummy")
os.environ.setdefault("SDL_AUDIODRIVER", "dummy")

import pygame

SPRITE_FRAMES_VA = 0x418458
SPRITE_FRAMES_COUNT = 216
BUILDING_PIECES_VA = 0x418348
BUILDING_PIECES_COUNT = 27
RECORD_FORMAT = "<5h"
RECORD_SIZE = struct.calcsize(RECORD_FORMAT)
CELL_PIXELS = 8

REPO_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ATLAS_PATH = os.path.join(REPO_ROOT, "Data", "felix0.png")
OUTPUT_DIR = os.path.join(REPO_ROOT, "docs", "ghidra-output", "pass4")
EXE_TABLES_PATH = os.path.join(REPO_ROOT, "src", "exe_tables.py")

FRAMES_PER_SHEET = 56
SHEET_COLUMNS = 8
CELL_BOX = 96
LABEL_HEIGHT = 24


def virtual_address_to_offset(exe_bytes, virtual_address):
    pe_header = struct.unpack_from("<I", exe_bytes, 0x3C)[0]
    if exe_bytes[pe_header:pe_header + 4] != b"PE\0\0":
        raise ValueError("not a PE file")
    section_count = struct.unpack_from("<H", exe_bytes, pe_header + 6)[0]
    optional_header_size = struct.unpack_from("<H", exe_bytes, pe_header + 20)[0]
    image_base = struct.unpack_from("<I", exe_bytes, pe_header + 24 + 28)[0]
    relative_address = virtual_address - image_base if virtual_address >= image_base else virtual_address
    section_table = pe_header + 24 + optional_header_size
    for index in range(section_count):
        name, virtual_size, section_va, raw_size, raw_offset = struct.unpack_from(
            "<8sIIII", exe_bytes, section_table + index * 40)
        if section_va <= relative_address < section_va + max(virtual_size, raw_size):
            return raw_offset + relative_address - section_va
    raise ValueError(f"VA {virtual_address:#x} is not inside any section")


def read_records(exe_bytes, virtual_address, count):
    offset = virtual_address_to_offset(exe_bytes, virtual_address)
    records = []
    for index in range(count):
        record = struct.unpack_from(RECORD_FORMAT, exe_bytes, offset + index * RECORD_SIZE)
        if record[0] != index:
            raise AssertionError(
                f"misaligned table at {virtual_address:#x}: record {index} has id {record[0]}")
        records.append(record)
    return records


def to_pixels(records):
    return [tuple(value * CELL_PIXELS for value in record[1:]) for record in records]


def write_exe_tables(frames, pieces):
    def format_tuple(entries):
        return "\n".join(f"    {entry}," for entry in entries)
    with open(EXE_TABLES_PATH, "w") as handle:
        handle.write(
            "# Generated by tools/decode_exe_tables.py -- do not edit.\n"
            f"# Source: FixitFelixJr.exe. SPRITE_FRAMES = {SPRITE_FRAMES_COUNT} records at "
            f"VA {SPRITE_FRAMES_VA:#x}; BUILDING_PIECES = {BUILDING_PIECES_COUNT} records at "
            f"VA {BUILDING_PIECES_VA:#x}.\n"
            "# Entries are (x, y, w, h) in atlas pixels (exe cells x 8), indexed by the exe's own ids.\n\n"
            f"SPRITE_FRAMES = (\n{format_tuple(frames)}\n)\n\n"
            f"BUILDING_PIECES = (\n{format_tuple(pieces)}\n)\n")


def write_json(filename, records):
    with open(os.path.join(OUTPUT_DIR, filename), "w") as handle:
        json.dump([list(record) for record in records], handle)


def draw_sheet(atlas, entries, first_id, path, columns, box):
    font = pygame.font.Font(None, 14)
    rows = (len(entries) + columns - 1) // columns
    sheet = pygame.Surface((columns * box, rows * (box + LABEL_HEIGHT)), pygame.SRCALPHA)
    sheet.fill((40, 40, 48, 255))
    for position, (x, y, w, h) in enumerate(entries):
        cell_x = (position % columns) * box
        cell_y = (position // columns) * (box + LABEL_HEIGHT)
        crop = atlas.subsurface(pygame.Rect(x, y, w, h))
        scale = min(1.0, (box - 4) / max(w, 1), (box - 4) / max(h, 1))
        if scale < 1.0:
            crop = pygame.transform.smoothscale(
                crop, (max(1, int(w * scale)), max(1, int(h * scale))))
        pygame.draw.rect(sheet, (90, 90, 110), (cell_x, cell_y, box, box), 1)
        sheet.blit(crop, (cell_x + 2, cell_y + 2))
        sheet.blit(font.render(f"#{first_id + position}", True, (255, 255, 255)),
                   (cell_x + 2, cell_y + box + 1))
        sheet.blit(font.render(f"({x},{y}) {w}x{h}", True, (200, 200, 160)),
                   (cell_x + 2, cell_y + box + 11))
    pygame.image.save(sheet, path)


def main(exe_path):
    with open(exe_path, "rb") as handle:
        exe_bytes = handle.read()
    try:
        frame_records = read_records(exe_bytes, SPRITE_FRAMES_VA, SPRITE_FRAMES_COUNT)
        piece_records = read_records(exe_bytes, BUILDING_PIECES_VA, BUILDING_PIECES_COUNT)
    except AssertionError as error:
        print(error, file=sys.stderr)
        return 1
    frames = to_pixels(frame_records)
    pieces = to_pixels(piece_records)
    write_exe_tables(frames, pieces)
    write_json("frame_table.json", frame_records)
    write_json("building_table.json", piece_records)

    pygame.display.init()
    pygame.font.init()
    pygame.display.set_mode((1, 1))
    atlas = pygame.image.load(ATLAS_PATH).convert_alpha()
    for first_id in range(0, SPRITE_FRAMES_COUNT, FRAMES_PER_SHEET):
        chunk = frames[first_id:first_id + FRAMES_PER_SHEET]
        draw_sheet(atlas, chunk, first_id,
                   os.path.join(OUTPUT_DIR, f"frames_{first_id:03d}.png"), SHEET_COLUMNS, CELL_BOX)
    draw_sheet(atlas, pieces, 0, os.path.join(OUTPUT_DIR, "building_table.png"), 6, 160)
    print(f"wrote {len(frames)} frames and {len(pieces)} building pieces")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    sys.exit(main(sys.argv[1]))
